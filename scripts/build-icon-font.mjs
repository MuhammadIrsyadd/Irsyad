// Material Symbols ships ~4MB of glyphs; Google Fonts can serve only the
// icons we actually use via `icon_names=`. This scans src/ for every
// lowercase identifier-looking string (icon names are plain snake_case
// ligatures) and writes the subset stylesheet URL to src/lib/icon-font.ts.
// Unknown names are ignored by Google, so over-matching is harmless.
// Runs automatically before `dev` and `build` — new icons just work.
import fs from "node:fs";
import path from "node:path";

const root = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1")), "..");
const srcDir = path.join(root, "src");
const outFile = path.join(srcDir, "lib", "icon-font.ts");

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]
  );
}

const names = new Set();
for (const file of walk(srcDir)) {
  if (!/\.(tsx?|mdx?)$/.test(file) || file === outFile) continue;
  const text = fs.readFileSync(file, "utf8");
  // quoted strings: "folder_open", 'mail', `explore`
  for (const m of text.matchAll(/["'`]([a-z][a-z0-9_]{1,39})["'`]/g)) names.add(m[1]);
  // JSX text children: <span ...>wifi</span>
  for (const m of text.matchAll(/>\s*([a-z][a-z0-9_]{1,39})\s*</g)) names.add(m[1]);
}

const list = [...names].sort();
const url =
  "https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@20..48,100..700,0..1,-50..200" +
  `&icon_names=${list.join(",")}&display=block`;

const out = `// Generated by scripts/build-icon-font.mjs — do not edit by hand.\nexport const ICON_FONT_URL =\n  ${JSON.stringify(url)};\n`;
if (!fs.existsSync(outFile) || fs.readFileSync(outFile, "utf8") !== out) fs.writeFileSync(outFile, out);
console.log(`icon font: ${list.length} candidate names, url ${url.length} chars`);
